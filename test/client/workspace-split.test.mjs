import test from 'node:test';
import assert from 'node:assert/strict';
import { captureNodes, flush, hookRunner, CLIENT_SOURCE } from '../../test-support/client.mjs';
import { normalizeWorkspaceDisplay, selectWorkspace, toggleWorkspacePin, workspacePaneIds } from '../../src/client/panel/workspace-display.js';
import { WORKSPACE_ALL_ID as ALL } from '../../src/client/constants.js';

const items = ['a', 'b', 'c'].map((id) => ({ id, path: id, color: 'mist' }));
const start = { items, activeId: ALL, pinnedIds: [], companionId: null, split: 0.5 };

test('双屏切换只替换有焦点的一侧，点击已显示空间只改变焦点，关闭后保留当前空间', () => {
  const single = selectWorkspace(selectWorkspace(start, 'a'), 'b');
  assert.deepEqual(workspacePaneIds(single), ['b']);
  const initial = toggleWorkspacePin(single);
  assert.deepEqual(workspacePaneIds(initial), ['b', 'a']);
  let state = selectWorkspace(initial, 'a');
  assert.deepEqual(workspacePaneIds(state), ['b', 'a'], '点击另一侧已显示空间不会交换位置');
  assert.equal(state.activeId, 'a');
  state = selectWorkspace(state, 'c');
  assert.deepEqual(workspacePaneIds(state), ['b', 'c'], '右侧有焦点，只换右侧');
  assert.equal(state.activeId, 'c');
  state = selectWorkspace(selectWorkspace(state, 'b'), ALL);
  assert.deepEqual(workspacePaneIds(state), [ALL, 'c'], '左侧有焦点，只换左侧');
  assert.equal(selectWorkspace(state, 'missing'), state);
  state = toggleWorkspacePin(selectWorkspace(state, 'c'));
  assert.deepEqual(workspacePaneIds(state), ['c']);
  assert.deepEqual(state.pinnedIds, []);
  assert.deepEqual(workspacePaneIds(toggleWorkspacePin(state)), ['c', ALL]);
  assert.deepEqual(workspacePaneIds(selectWorkspace(state, 'a')), ['a']);
  const onlyMain = { ...start, items: [] };
  assert.equal(toggleWorkspacePin(onlyMain), onlyMain, '只有一个空间时不能开启分屏');
});

test('兼容旧存档：单固定项补齐双屏；只剩主空间时恢复为单屏；失效选项不点亮', () => {
  assert.deepEqual(normalizeWorkspaceDisplay(items, { pinnedIds: ['a'], activeId: 'a', companionId: 'c', split: 0.65 }),
    { pinnedIds: ['a', 'c'], activeId: 'a', companionId: null, split: 0.65 });
  assert.deepEqual(normalizeWorkspaceDisplay(items, { pinnedIds: ['a'], activeId: 'b', companionId: 'c' }).pinnedIds, ['a', 'b']);
  assert.deepEqual(normalizeWorkspaceDisplay(items, { pinnedIds: [ALL, 'missing'], activeId: ALL }).pinnedIds, [ALL, 'a']);
  assert.deepEqual(normalizeWorkspaceDisplay(items, { pinnedIds: ['missing', 'b'], activeId: 'b' }).pinnedIds, [ALL, 'b']);
  assert.deepEqual(normalizeWorkspaceDisplay([], { pinnedIds: [ALL, 'missing'], activeId: 'missing' }).pinnedIds, []);
  assert.deepEqual(normalizeWorkspaceDisplay(items, { pinnedIds: ['missing'], activeId: 'missing' }).activeId, ALL);
});

test('面板：两墙各自筛选，焦点控制捕获目标，固定与分隔线在仓库本地恢复', async (t) => {
  const runner = hookRunner(t), { api } = runner;
  const requested = [];
  const notes = ['a/a.md', 'b/b.md', 'c/c.md', 'main/main.md'].map((relPath) => ({ path: '/vault/' + relPath, relPath, title: relPath, created: Date.now() }));
  api.writeStoredWorkspaces('/vault', items, 'a', 'paper', { pinnedIds: ['a', 'b'], split: 0.5 });
  runner.connect(async (_channel, endpoint, payload) => {
    requested.push([endpoint, payload]);
    return { ok: true, value: endpoint === 'state' ? { configured: true, revision: '1', notes, jobs: [], settings: { vaultPath: '/vault', notesDir: '/vault/main' } } : {} };
  });
  const translate = (key) => key;
  const keys = new Map(), doc = { body: {}, defaultView: { addEventListener() {}, removeEventListener() {} },
    addEventListener: (key, fn) => keys.set(key, fn), removeEventListener: (key) => keys.delete(key) };
  const panel = { ownerDocument: doc, querySelector: () => null, setAttribute() {}, removeAttribute() {} };
  const key = (digit) => keys.get('keydown')({ key: digit, metaKey: true, target: doc.body, preventDefault() {}, stopPropagation() {} });
  const render = () => captureNodes(runner.render(api.components.StickyNotesPanel, { t: translate }, (tree) => { tree.props.ref.current = panel; }));
  const type = (nodes, name) => nodes.find((node) => node.type === api.components[name]);
  const walls = (nodes) => nodes.filter((node) => node.props.className === 'SN_workspacePane');
  const wallNotes = (nodes) => walls(nodes).map((wall) => captureNodes(wall).filter((node) => node.type === api.components.NoteCard).map((node) => node.props.note.relPath));
  render(); await flush();
  let nodes = render();
  assert.deepEqual(wallNotes(nodes), [['a/a.md'], ['b/b.md']]);
  assert.equal(type(nodes, 'CaptureComposer').props.captureWorkspace, 'a');
  const paneProps = walls(nodes)[1].props;
  paneProps.onPointerDownCapture({ button: 0 });
  nodes = render();
  assert.equal(type(nodes, 'CaptureComposer').props.captureWorkspace, 'b');
  await type(nodes, 'CaptureComposer').props.onCreate({ title: '新建' });
  assert.equal(requested.at(-1)[1].targetDir, '/vault/b');
  const splitter = nodes.find(({ props }) => props.role === 'separator');
  assert.equal(splitter.props['aria-valuenow'], 50);
  splitter.props.onKeyDown({ key: 'ArrowRight', preventDefault() {} });
  nodes = render();
  assert.equal(nodes.find(({ props }) => props.role === 'separator').props['aria-valuenow'], 55);
  assert.equal(api.readStoredWorkspaces('/vault').split, 0.55);
  assert.equal(api.readStoredWorkspaces('/other').split, 0.5);
  type(nodes, 'WorkspaceBar').props.onSelect('c');
  nodes = render();
  assert.deepEqual(wallNotes(nodes), [['a/a.md'], ['c/c.md']], '右侧有焦点，点标签只替换右侧');
  assert.equal(type(nodes, 'WorkspaceBar').props.pinActive, true);
  assert.equal(type(nodes, 'CaptureComposer').props.captureWorkspace, 'c');
  assert.deepEqual(type(nodes, 'WorkspaceBar').props.visibleIds, ['a', 'c']);
  walls(nodes)[0].props.onFocusCapture();
  nodes = render();
  key('3'); // 主空间、A、B、C；从键盘选择 B 只切换左侧。
  nodes = render();
  assert.deepEqual(wallNotes(nodes), [['b/b.md'], ['c/c.md']]);
  assert.equal(type(nodes, 'CaptureComposer').props.captureWorkspace, 'b');
  assert.equal(type(nodes, 'NoteDrawer'), undefined, 'Cmd+数字不会打开便签');
  assert.deepEqual(api.readStoredWorkspaces('/vault').pinnedIds, ['b', 'c']);
  walls(nodes)[1].props.onFocusCapture();
  nodes = render();

  type(nodes, 'WorkspaceBar').props.onTogglePin();
  nodes = render();
  assert.equal(type(nodes, 'WorkspaceBar').props.pinActive, false);
  assert.deepEqual(type(nodes, 'WorkspaceBar').props.visibleIds, ['c']);
  assert.deepEqual(wallNotes(nodes), [['c/c.md']]);
  assert.equal(nodes.some(({ props }) => props.role === 'separator'), false);
  assert.deepEqual(api.readStoredWorkspaces('/vault').pinnedIds, []);
  assert.equal(api.readStoredWorkspaces('/vault').activeId, 'c');
  assert.deepEqual(workspacePaneIds(api.readStoredWorkspaces('/vault')), ['c'], '重新读取不会恢复第二个亮起的标签');

  type(nodes, 'WorkspaceBar').props.onTogglePin();
  nodes = render();
  assert.deepEqual(wallNotes(nodes), [['c/c.md'], ['b/b.md']]);
  type(nodes, 'WorkspaceBar').props.onRemove('c');
  nodes = render();
  assert.deepEqual(type(nodes, 'WorkspaceBar').props.visibleIds, [ALL, 'b']);
  assert.equal(type(nodes, 'WorkspaceBar').props.pinActive, true);
  assert.equal(type(nodes, 'CaptureComposer').props.captureWorkspace, 'b');
  type(nodes, 'WorkspaceBar').props.onRemove('a');
  nodes = render();
  type(nodes, 'WorkspaceBar').props.onRemove('b');
  nodes = render();
  assert.deepEqual(type(nodes, 'WorkspaceBar').props.visibleIds, [ALL]);
  assert.equal(type(nodes, 'WorkspaceBar').props.pinActive, false);
});

test('唯一的全局分屏图标位于右端；单双屏状态与标签高亮一致', (t) => {
  const { api, render } = hookRunner(t), calls = [];
  const original = globalThis.document;
  globalThis.document = { addEventListener() {}, removeEventListener() {} };
  t.after(() => { globalThis.document = original; });
  const entries = items.map((item) => ({ ...item, label: item.id }));
  const props = { entries, activeId: 'b', visibleIds: ['a', 'b'], pinActive: true,
    t: (key) => key, onTogglePin: () => calls.push('toggle') };
  const tabs = (nodes) => nodes.filter((node) => node.props.role === 'tab');
  const splitButtons = (nodes) => nodes.filter((node) => node.props.className === 'SN_wsTool SN_wsSplit');
  const selected = (nodes) => tabs(nodes).map((node) => node.props['aria-selected']);
  const hint = (nodes) => nodes.find((node) => node.props.className === 'SN_shortcutKey SN_wsSplitHint');
  let nodes = captureNodes(render(api.components.WorkspaceBar, props));
  assert.deepEqual(selected(nodes), ['true', 'true', 'false']);
  assert.deepEqual(tabs(nodes).map((node) => node.props.tabIndex), [-1, 0, -1]);
  assert.deepEqual(tabs(nodes).map((node) => node.props['aria-keyshortcuts']), ['Meta+1', 'Meta+2', 'Meta+3']);
  assert.deepEqual(tabs(nodes).map((node) => captureNodes(node).find(({ type }) => type === 'kbd').children[0]), ['⌘1', '⌘2', '⌘3']);
  assert.deepEqual(hint(nodes).children.map(({ children }) => children[0]), ['workspace.splitUnlockHint', '⌘;']);
  assert.equal(splitButtons(nodes).length, 1);
  assert.equal(splitButtons(nodes)[0].props['aria-pressed'], true);
  assert.equal(splitButtons(nodes)[0].props['data-active'], 'true');
  assert.equal(splitButtons(nodes)[0].props['aria-keyshortcuts'], 'Meta+;');
  assert.equal(splitButtons(nodes)[0].props.title, 'workspace.splitClose');
  const glyph = splitButtons(nodes)[0].children[0];
  assert.equal(glyph.type.name, 'SplitViewIcon');
  const svg = glyph.type(glyph.props);
  assert.equal(svg.type, 'svg');
  assert.equal(svg.props.stroke, 'currentColor');
  assert.deepEqual(svg.children.map(({ type }) => type), ['rect', 'path']);
  assert.equal(svg.children[1].props.d, 'M12 5v14', '窗口中央是左右分割线');
  splitButtons(nodes)[0].props.onClick();
  assert.deepEqual(calls, ['toggle']);

  nodes = captureNodes(render(api.components.WorkspaceBar, { ...props, visibleIds: ['b'], pinActive: false }));
  assert.deepEqual(selected(nodes), ['false', 'true', 'false']);
  assert.equal(splitButtons(nodes).length, 1);
  assert.equal(splitButtons(nodes)[0].props['aria-pressed'], false);
  assert.equal(splitButtons(nodes)[0].props['data-active'], 'false');
  assert.equal(splitButtons(nodes)[0].props.title, 'workspace.splitOpen');
  assert.deepEqual(hint(nodes).children.map(({ children }) => children[0]), ['workspace.splitLockHint', '⌘;']);
  const allTabs = [...entries, ...Array.from({ length: 7 }, (_, index) => ({ id: 'extra' + index, label: 'Extra', path: 'extra/' + index }))];
  const long = captureNodes(render(api.components.WorkspaceBar, { ...props, entries: allTabs }));
  assert.equal(tabs(long)[8].props['aria-keyshortcuts'], 'Meta+9');
  assert.equal(tabs(long)[9].props['aria-keyshortcuts'], undefined);
  const single = captureNodes(render(api.components.WorkspaceBar, { ...props, entries: [entries[1]], visibleIds: ['b'], pinActive: false }));
  assert.equal(splitButtons(single).length, 1);
  assert.equal(splitButtons(single)[0].props.disabled, true);
  assert.equal(splitButtons(single)[0].props['aria-keyshortcuts'], undefined);
  assert.match(CLIENT_SOURCE, /\.SN_wsSplitControl\{[^}]*margin-left:auto/);
  assert.match(CLIENT_SOURCE, /\.SN_wsSplit\[data-active='true'\]\{color:var\(--sn-accent\);background:transparent\}/);
});

test('标签排序：鼠标直接横拖，轻点不拦截，触屏短滑滚动、长按拖动', (t) => {
  const runner = hookRunner(t), { api } = runner;
  const listeners = new Map(), moved = [], captures = [];
  const original = globalThis.document;
  globalThis.document = { addEventListener: (key, fn) => listeners.set(key, fn), removeEventListener: (key) => listeners.delete(key) };
  globalThis.window.addEventListener = () => {};
  globalThis.window.removeEventListener = () => {};
  t.after(() => { runner.unmount(); globalThis.document = original; });
  t.mock.timers.enable({ apis: ['setTimeout'] });
  const entries = [{ id: ALL }, ...items];
  const strip = { scrollLeft: 0, getBoundingClientRect: () => ({ left: 0, right: 260, width: 260 }),
    querySelectorAll: () => entries.map(({ id }, index) => ({ getAttribute: () => id, getBoundingClientRect: () => ({ left: 60 * index, right: 60 * (index + 1) }) })) };
  const props = { entries, stripRef: { current: strip }, onReorder: (...args) => moved.push(args) };
  const render = () => runner.render(api.hooks.useWorkspaceReorder, props);
  const event = { button: 0, clientX: 90, clientY: 12, pointerType: 'mouse', pointerId: 1, currentTarget: { setPointerCapture: (id) => captures.push(id) } };
  render().startPress(event, entries[0]);
  assert.equal(listeners.has('pointermove'), false, '主空间固定首位');
  render().startPress(event, items[0]);
  listeners.get('pointermove')({ ...event, clientX: 95 });
  assert.equal(render().drag, null);
  listeners.get('pointerup')({ ...event, clientX: 95 });
  assert.equal(render().consumeClick(), false, '轻点加少量抖动仍切换空间');
  assert.deepEqual(captures, []);
  render().startPress(event, items[0]);
  listeners.get('pointermove')({ ...event, clientY: 23 });
  assert.equal(render().drag, null, '纵向移动不触发排序');
  render().startPress(event, items[0]);
  let prevented = false;
  listeners.get('pointermove')({ ...event, clientX: 186, preventDefault: () => { prevented = true; } });
  assert.equal(prevented, true);
  assert.deepEqual(captures, [1]);
  assert.deepEqual(render().drag, { id: 'a', dx: 96, insertAt: 1, caretX: 180 }, '横拖立即跟手并显示插入线，无需等长按');
  assert.deepEqual(moved, [], '松手之前不修改顺序');
  listeners.get('pointerup')({ ...event, pointerId: 2, clientX: 230 });
  assert.ok(render().drag, '其他指针不能结束当前拖拽');
  listeners.get('pointerup')({ ...event, clientX: 230 });
  assert.deepEqual(moved, [['a', 2]]);
  assert.equal(render().consumeClick(), true);
  render().startPress({ ...event, pointerType: 'touch' }, items[0]);
  listeners.get('pointermove')({ ...event, clientX: 55 });
  assert.equal(strip.scrollLeft, 35);
  listeners.get('pointerup')({ ...event, clientX: 55 });
  assert.equal(render().consumeClick(), true);
  assert.deepEqual(moved, [['a', 2]]);
  assert.deepEqual(captures, [1], '触屏短滑不进入拖动排序');
  const held = { ...event, pointerType: 'touch', clientX: 212 };
  render().startPress(held, items[2]);
  t.mock.timers.tick(api.WORKSPACE_HOLD_MS);
  assert.equal(render().drag?.id, 'c');
  listeners.get('pointermove')({ ...held, clientX: 10 });
  listeners.get('pointerup')({ ...held, clientX: 10 });
  assert.deepEqual(moved, [['a', 2], ['c', 0]], '触屏仍支持长按后拖动');
  assert.match(CLIENT_SOURCE, /SN_wsTab\[data-all='false'\]\{touch-action:pan-y/);
});
