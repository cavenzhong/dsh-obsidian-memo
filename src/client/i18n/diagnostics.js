const templates = [
  [/^同名便签已存在：([\s\S]+)；正文已保存在原文件中$/, (_, name) => `A note named ${name} already exists. The body was saved in the original file.`],
  [/^读不到默认工作空间：([\s\S]+)（([\s\S]+)）$/, (_, path, detail) => `Could not read the default workspace: ${path} (${translate(detail)})`],
  [/^单张图片不能超过 (.+)$/, (_, size) => `Each image must be at most ${size}`],
  [/^图片合计不能超过 (.+)$/, (_, size) => `Images must total at most ${size}`],
  [/^本地图片超过读取上限（(.+)）$/, (_, size) => `The local image exceeds the ${size} read limit`],
  [/^文件名不能超过 (\d+) 字节$/, (_, count) => `The filename must be at most ${count} bytes`],
  [/^每篇便签最多添加 (\d+) 张图片$/, (_, count) => `Add up to ${count} images per note`],
  [/^删除中断，部分文件保留在 ([\s\S]+)，请按 restore\.json 找回；([\s\S]+)$/, (_, path, detail) => `Deletion was interrupted. Some files remain at ${path}; use restore.json to recover them. ${detail}`],
  [/^撤回中断，部分文件已回到原位，其余保留在 ([\s\S]+)；请按 restore\.json 找回$/, (_, path) => `Undo was interrupted. Some files were restored; the rest remain at ${path}. Use restore.json to recover them.`],
  [/^移至系统垃圾桶失败，仓库回收文件仍保留在 ([\s\S]+?)：([\s\S]+)$/, (_, path, detail) => `Could not move files to the system trash. They remain at ${path}: ${detail}`],
  [/^method (.+) 与路径 (.+) 不匹配$/, (_, method, path) => `Method ${method} does not match path ${path}`],
];

function translate(text, depth = 0) {
  if (messages.has(text)) return messages.get(text);
  for (const [pattern, render] of templates) if (pattern.test(text)) return text.replace(pattern, render);
  for (const [prefix, label, nested] of prefixes) {
    if (!text.startsWith(prefix)) continue;
    const detail = text.slice(prefix.length);
    return label + (nested && depth < 3 ? translate(detail, depth + 1) : detail);
  }
  return text;
}

function formatDiagnostic(t, text) {
  if (text === 'error.offline' || text === 'error.failed') return t?.(text) || text;
  return typeof text === 'string' && t?.('ui.locale') === 'en' ? translate(text) : text;
}

