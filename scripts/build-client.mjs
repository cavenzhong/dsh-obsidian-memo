import { build, context } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const target = new URL('../lib/client.js', import.meta.url)
const options = {
  absWorkingDir: root,
  entryPoints: ['src/client/index.js'],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  external: ['react', 'react-dom'],
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: `// Generated by pnpm build. Edit src/client/, then rebuild.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-obsidian-memo',\n  factory: (require) => {\n    const module = { exports: {} };\n    const exports = module.exports;` },
  footer: { js: '    return module.exports;\n  },\n});' },
  outfile: fileURLToPath(target),
}

if (process.argv.includes('--watch')) {
  const watcher = await context(options)
  await watcher.watch()
  console.info('Watching src/client/ → lib/client.js')
} else {
  const result = await build({ ...options, write: false })
  const output = result.outputFiles[0].text
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== output) {
      console.error('lib/client.js is out of date. Run pnpm build and include the generated file.')
      process.exitCode = 1
    }
  } else {
    await writeFile(target, output)
    console.info('Built lib/client.js from src/client/')
  }
}
